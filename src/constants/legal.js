// Convenience accessor: getDisclaimer('medical', 'tr') -> { title, body }
// Falls back to English, then to the medical variant, so callers always get
// a valid { title, body } object.
export function getDisclaimer(variant = 'medical', language = 'en') {
  const group = DISCLAIMERS[variant] || DISCLAIMERS.medical;
  return group[language] || group.en;
}

