// Shared compliance / legal building blocks for GLP-1 Coach.
//
// Centralizes the configurable legal URLs and the bilingual (en/tr) disclaimer
// copy required for App Store review (Guideline 1.4.1 medical-harm disclaimers,
// AI-estimate accuracy, and data-sent-to-server transparency — report D3/D4).
//
// URLs are placeholders by default but can be overridden per-build via
// app config: app.json / app.config.js -> expo.extra. Example:
//
//   {
//     "expo": {
//       "extra": {
//         "supportUrl": "https://example.com/support",
//         "privacyUrl": "https://example.com/privacy",
//         "termsUrl":   "https://example.com/terms"
//       }
//     }
//   }
//
// Everything here is plain data so it can be imported from anywhere (screens,
// components, services) without pulling in React.

import Constants from 'expo-constants';

// expo-constants surfaces app config under expoConfig (SDK 46+) with a
// legacy `manifest` fallback. Guard every access so a missing field never throws.
const extra =
  (Constants &&
    ((Constants.expoConfig && Constants.expoConfig.extra) ||
      (Constants.manifest && Constants.manifest.extra))) ||
  {};

// Placeholder fallbacks — swap the real URLs in via expo.extra (above) at build
// time. Kept as obvious placeholders so they are easy to spot if shipped as-is.
const DEFAULTS = {
  supportUrl: 'https://example.com/glp1-coach/support',
  privacyUrl: 'https://example.com/glp1-coach/privacy',
  termsUrl: 'https://example.com/glp1-coach/terms',
};

export const SUPPORT_URL = extra.supportUrl || DEFAULTS.supportUrl;
export const PRIVACY_URL = extra.privacyUrl || DEFAULTS.privacyUrl;
export const TERMS_URL = extra.termsUrl || DEFAULTS.termsUrl;

